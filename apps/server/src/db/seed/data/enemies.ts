/**
 * Base stats are quoted at level 60 — the same anchor convention champions use — and a
 * stage scales them down to whatever level its wave asks for.
 */
const enemy = (
  key: string,
  name: string,
  archetype: string,
  element: EnemyDefInput['element'],
  role: EnemyDefInput['role'],
  stats: EnemyDefInput['baseStats'],
  skills: string[],
  sortOrder: number,
  extra: Partial<EnemyDefInput> = {},
): EnemyDefInput => ({
  key,
  name,
  archetype,
  element,
  role,
  baseStats: stats,
  growth: 1.045,
  skills,
  assetKey: 'enemy_lizard',
  isBoss: false,
  bossMechanics: { almightyImmunity: false, tmReductionImmune: false },
  sortOrder,
  ...extra,
});

