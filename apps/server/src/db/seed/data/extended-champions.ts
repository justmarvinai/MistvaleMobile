/**
 * The thirty art-pending roster champions, plus the six food units.
 *
 * One entry per row of docs/CONTENT_PLAN_EA01.md §1b: faction, element, role and rarity
 * are transcribed from that table, and every kit is built around the row's "kit hook"
 * column, so the design doc and the game agree. The showcase seven (final art, full kits
 * in §1) live in `showcase-champions.ts`; the food units close out §1b.
 *
 * **Placeholder-art convention (docs/ASSET_GUIDE.md).** None of these champions has art
 * yet, so all of them point at the shared `enemy_lizard` asset — the territorial-lizard
 * model, differentiated in-game by per-champion tint and a framed tinted avatar. When a
 * real sprite is uploaded through the Admin asset manager the registry reference swaps
 * and every screen updates: no code, no redeploy. Mechanics are final regardless.
 *
 * Numbers follow docs/COMBAT_SYSTEM.md: base stats are ★6/L60/Asc6 anchors on the §1
 * role bands scaled by rarity (Legendary ≈ Epic ×1.08, Rare ×0.88, Uncommon ×0.72,
 * Common ×0.55); damage multipliers sit in the §6 bands (A1 ×1.7–2.2 ATK, AoE ×2.0–2.6,
 * single-target nukes ×3.5–6.5, DEF-scalers ×3.2–4.2 DEF, HP-scalers ×0.20–0.26 MaxHP
 * per hit); statuses come from the §7 catalogue seeded in `statuses.ts`.
 *
 * `chance` is a fraction, not a percentage (0.75 = 75%), and is rolled *before* the
 * ACC-versus-RES contest the engine applies on top (§5). Buffs never carry a chance.
 *
 * Skill keys are `<championKey>_<slot>_<shortName>`; skill `sortOrder` is the slot index
 * (A1 = 1), champion `sortOrder` continues the showcase seven at 8 and ends with the
 * food units.
 *
 * The seed types are the schema *input* types, matching the rest of this directory, but
 * every schema-defaulted field (`hits`, effect `target`, `sortOrder`, `isFood`, …) is
 * written out anyway so a seed row reads exactly as the row the database will hold.
 * `extended-champions.test.ts` parses all of it through `championDefSchema` /
 * `skillDefSchema`, which is the guarantee that actually matters.
 */

