import type { StatusDefInput } from '@mistvale/shared';

/**
 * The EA status catalogue — 13 buffs and 15 debuffs.
 *
 * Values and timings follow docs/COMBAT_SYSTEM.md §7. Each entry maps to an
 * `engineType` the engine implements; publish validation rejects anything else, so a
 * status can never exist that no code backs.
 *
 * `family` + `potency` drive stacking: a stronger member replaces a weaker one, an equal
 * member refreshes its duration.
 */

const buff = (
  key: string,
  name: string,
  engineType: StatusDefInput['engineType'],
  family: string,
  potency: number,
  params: StatusDefInput['params'],
  description: string,
  sortOrder: number,
): StatusDefInput => ({
  key,
  name,
  kind: 'buff',
  engineType,
  family,
  potency,
  params,
  icon: `mv-buff-${family}`,
  description,
  sortOrder,
});

